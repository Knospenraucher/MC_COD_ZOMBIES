DRUM = {"weevil", "dingo", "rpk", "hg_40"}
# Formen, die nicht der Klasse folgen
SHAPE_OF = {"ray_gun_mk2": "ray_gun", "wunderwaffe_dg2": "wunderwaffe_dg2", "thundergun": "thundergun",
            "annihilator": "annihilator", "ray_gun": "ray_gun"}


def shade(color, factor):
    return tuple(max(0, min(255, int(c * factor))) for c in color)


def draw(gun_id, category):
    rows = SHAPES[SHAPE_OF.get(gun_id, category)].strip("\n").split("\n")
    grid = [list(r) for r in rows]
    if gun_id in SCOPE and category != "sniper":
        for x in range(6, 11):
            grid[4][x] = "s"
        grid[5][7] = grid[5][9] = "s"
    if gun_id in DRUM:
        for y in range(9, 12):
            for x in range(4, 9):
                grid[y][x] = "d"
    body, dark, accent = WEAPON_COLORS.get(gun_id, PALETTES[category])
    colors = {
        "#": body,
        "d": dark,
        "a": accent,
        "s": shade(body, 1.9) if sum(body) < 400 else shade(body, 1.15),
        "g": GLOW.get(gun_id, accent),
    }
    img = Image.new("RGBA", (16, 16), (0, 0, 0, 0))
    for y, row in enumerate(grid):
        for x, ch in enumerate(row):
            if ch in colors:
                c = colors[ch]
                # obere Kante etwas heller, untere etwas dunkler: wirkt plastischer
                above = y > 0 and grid[y - 1][x] in colors
                below = y < 15 and grid[y + 1][x] in colors
                if not above:
                    c = shade(c, 1.25)
                elif not below:
                    c = shade(c, 0.8)
                img.putpixel((x, y), c + (255,))
    return img


def parse_catalog():
    src = open(CATALOG, encoding="utf-8").read()
    return re.findall(r'gun\("([a-z0-9_]+)", "([^"]+)", "([^"]+)", "([a-z]+)"\)', src)


def main():
    guns = parse_catalog()
    lang = {}
    for gun_id, name, pap, category in guns:
        draw(gun_id, category).save(os.path.join(ROOT, "textures", "item", gun_id + ".png"))
        with open(os.path.join(ROOT, "models", "item", gun_id + ".json"), "w") as f:
            json.dump({"parent": "minecraft:item/handheld", "textures": {"layer0": "mczombies:item/" + gun_id}}, f, indent=2)
        with open(os.path.join(ROOT, "items", gun_id + ".json"), "w") as f:
            json.dump({"model": {"type": "minecraft:model", "model": "mczombies:item/" + gun_id}}, f, indent=2)
        lang["item.mczombies." + gun_id] = name
        lang["item.mczombies." + gun_id + ".upgraded"] = pap
    for code in ("de_de", "en_us"):
        path = os.path.join(ROOT, "lang", code + ".json")
        data = json.load(open(path, encoding="utf-8"))
        data = {k: v for k, v in data.items() if not k.startswith("item.mczombies.")}
        data.update(lang)
        with open(path, "w", encoding="utf-8") as f:
            json.dump(data, f, indent=2, ensure_ascii=False)
            f.write("\n")
    print(len(guns), "Waffen")


if __name__ == "__main__":
    main()
